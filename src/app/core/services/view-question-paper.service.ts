import { Injectable, inject } from '@angular/core';
import { HttpClient } from '@angular/common/http';
import { Observable } from 'rxjs';
import { map } from 'rxjs/operators';
import { environment } from '../../../environments/environment';

// ─── Models ───────────────────────────────────────────────────────────────────

export interface QuestionPaperRubricDto {
  rubricId:        number;
  criterionOrder:  number;
  rubricText:      string;
  maxMarks:        number;
  isAutoGenerated: boolean;
}

export interface QuestionPaperDetailDto {
  questionNumber: number;
  questionText:   string;
  officialAnswer: string;
  maxMarks:       number;
  rubricAdded:    boolean;
  rubrics:        QuestionPaperRubricDto[];
}

export interface QuestionPaperViewDto {
  questionPaperId:       number;
  questionPaperName:     string;
  className:             string;
  subjectName:           string;
  examTypeName:          string;
  academicYear:          string;
  totalMarks:            number;
  totalQuestions:        number;
  answerSheetsSubmitted: boolean;
  examDate:              string | null;  // ISO date string from backend, null if not set
  isLocked:              boolean;        // computed by backend
  questions:             QuestionPaperDetailDto[];
}

// Row in the "All Subjects" summary table
export interface QuestionPaperSummaryDto {
  questionPaperId:       number;
  questionPaperName:     string;
  subjectName:           string;
  examTypeName:          string;
  totalMarks:            number;
  totalQuestions:        number;
  answerSheetsSubmitted: boolean;
  examDate:              string | null;  // ISO date string, null if not set
  isLocked:              boolean;        // computed by backend
}

// ─── Service ──────────────────────────────────────────────────────────────────

@Injectable({ providedIn: 'root' })
export class ViewQuestionPaperService {
  private http   = inject(HttpClient);
  private apiUrl = environment.apiUrl;

  getQuestionPaper(questionPaperId: number): Observable<QuestionPaperViewDto> {
    return this.http
      .get<{ success: boolean; data: any }>(
        `${this.apiUrl}/question-paper/${questionPaperId}`,
      )
      .pipe(map((res) => {
        const d = res.data;
        d.answerSheetsSubmitted = d.answerSheetsSubmitted ?? d.AnswerSheetsSubmitted ?? false;
        d.examDate              = d.examDate              ?? d.ExamDate              ?? null;
        d.isLocked              = d.isLocked              ?? d.IsLocked              ?? false;
        return d as QuestionPaperViewDto;
      }));
  }

  // Returns all question papers for a class (all subjects, all exam types)
  getAllPapersByClass(classId: number): Observable<QuestionPaperSummaryDto[]> {
    return this.http
      .get<{ success: boolean; data: any[] }>(
        `${this.apiUrl}/question-paper/by-class/${classId}`,
      )
      .pipe(map((res) => (res.data ?? []).map((d: any) => ({
        ...d,
        answerSheetsSubmitted: d.answerSheetsSubmitted ?? d.AnswerSheetsSubmitted ?? false,
        examDate:              d.examDate              ?? d.ExamDate              ?? null,
        isLocked:              d.isLocked              ?? d.IsLocked              ?? false,
      } as QuestionPaperSummaryDto))));
  }
}
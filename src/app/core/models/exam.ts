// ============================================
// EXAM / QUESTION PAPER CREATION MODELS
// ============================================

export type { QuestionPaperDto } from './common.models';

export interface RubricPoint {
  description: string;
  marks: number | null;
  isAutoGenerated?: boolean;
}

export interface QuestionSet {
  questionNumber: number;
  questionText: string;
  answerText: string;
  maxMarks: number | null;
  validationRulesCount: number | null;
  rubricPoints: RubricPoint[];
}

export interface Exam {
  questionPaperId: number;
  examTitle: string;
  examTypeName: string;
  examDate: string;
  sectionName: string;
  academicYear: string;
  classId: number;
}

export interface ExamFormData {
  academicYear: string;
  classId: string;
  subjectId: string;
  examTypeId: string;
  totalMarks: number | null;
  numberOfQuestions: number | null;
  questionSets: QuestionSet[];
  questionPaperName: string | null;
  /** Optional exam date — YYYY-MM-DD string or null */
  examDate: string | null;
}

export interface ExamFilters {
  filterExamClass: string;
  filterExamSubject: string;
  filterExamExamType: string;
}

export interface ExamRubric {
  criterionOrder: number;
  rubricText: string;
  maxMarks: number;
  /** True when the rubric was auto-generated for a 1-mark question */
  isAutoGenerated?: boolean;
}

export interface ExamQuestion {
  questionNumber: number;
  questionText: string;
  maxMarks: number;
  answerText: string;
  rubrics: ExamRubric[];
  /** False for auto-generated 1-mark questions, true otherwise */
  rubricAdded?: boolean;
}

export interface ExamApiRequest {
  classId: number;
  subjectId: number;
  examTypeId: number;
  totalMarks: number;
  questionPaperName: string;
  /** Optional exam date sent as ISO UTC string or null */
  examDate: string | null;
  questions: ExamQuestion[];
}